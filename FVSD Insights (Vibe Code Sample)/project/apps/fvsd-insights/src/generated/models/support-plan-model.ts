import type { Staff } from './staff-model';
import type { GradeBand } from './grade-band-model';
import type { InterventionTier } from './intervention-tier-model';
import type { ReportingPeriod } from './reporting-period-model';
import type { School } from './school-model';
import type { StudentGroup } from './student-group-model';

export const SupportPlanStatusKeyToLabel = {
  'Planned': 'Planned',
  'Active': 'Active',
  'Paused': 'Paused',
  'Completed': 'Completed',
  'Closed': 'Closed'
} as const;
export type SupportPlanStatusKey = keyof typeof SupportPlanStatusKeyToLabel;

export const SupportPlanSupportTypeKeyToLabel = {
  'Counselling': 'Counselling',
  'LearningSupport': 'Learning Support',
  'AttendanceOutreach': 'Attendance Outreach',
  'FamilyLiaison': 'Family Liaison',
  'BehaviourSupport': 'Behaviour Support'
} as const;
export type SupportPlanSupportTypeKey = keyof typeof SupportPlanSupportTypeKeyToLabel;

export interface SupportPlan {
  /**
   * @displayName Support Plan ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Support Plan Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  supportPlanName: string;
  /**
   * @displayName Average Days To Support
   * @validationRule Required for create/update operations
   */
  averageDaysToSupport: number;
  /**
   * @displayName Coordinator
   * @validationRule Required for create/update operations
   */
  coordinator: Pick<Staff, 'id' | 'staffName'>;
  /**
   * @displayName Effectiveness Rating
   * @validationRule Required for create/update operations
   */
  effectivenessRating: number;
  /**
   * @displayName Grade Band
   * @validationRule Required for create/update operations
   */
  gradeBand: Pick<GradeBand, 'id' | 'gradeBandName'>;
  /**
   * @displayName Intervention Tier
   * @validationRule Required for create/update operations
   */
  interventionTier: Pick<InterventionTier, 'id' | 'interventionTierName'>;
  /**
   * @displayName Referrals Completed
   * @validationRule Required for create/update operations
   */
  referralsCompleted: number;
  /**
   * @displayName Reporting Period
   * @validationRule Required for create/update operations
   */
  reportingPeriod: Pick<ReportingPeriod, 'id' | 'reportingPeriodName'>;
  /**
   * @displayName School
   * @validationRule Required for create/update operations
   */
  school: Pick<School, 'id' | 'schoolName'>;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: SupportPlanStatusKey;
  /**
   * @displayName Student Group
   * @validationRule Required for create/update operations
   */
  studentGroup: Pick<StudentGroup, 'id' | 'studentGroupName'>;
  /**
   * @displayName Students Supported
   * @validationRule Required for create/update operations
   */
  studentsSupported: number;
  /**
   * @displayName Support Type
   * @validationRule Required for create/update operations
   */
  supportTypeKey: SupportPlanSupportTypeKey;
}

export const _SupportPlan = 'SupportPlan' as const;