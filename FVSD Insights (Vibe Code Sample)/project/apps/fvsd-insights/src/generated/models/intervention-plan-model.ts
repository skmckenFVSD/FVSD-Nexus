import type { GradeBand } from './grade-band-model';
import type { InterventionTier } from './intervention-tier-model';
import type { Staff } from './staff-model';
import type { Program } from './program-model';
import type { School } from './school-model';
import type { SchoolYear } from './school-year-model';
import type { StudentGroup } from './student-group-model';

export const InterventionPlanFocusAreaKeyToLabel = {
  'Attendance': 'Attendance',
  'Literacy': 'Literacy',
  'Numeracy': 'Numeracy',
  'Wellbeing': 'Wellbeing',
  'CreditCompletion': 'Credit Completion'
} as const;
export type InterventionPlanFocusAreaKey = keyof typeof InterventionPlanFocusAreaKeyToLabel;

export const InterventionPlanStatusKeyToLabel = {
  'Planned': 'Planned',
  'Active': 'Active',
  'Paused': 'Paused',
  'Completed': 'Completed',
  'Closed': 'Closed'
} as const;
export type InterventionPlanStatusKey = keyof typeof InterventionPlanStatusKeyToLabel;

export interface InterventionPlan {
  /**
   * @displayName Intervention Plan ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Intervention Plan Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  interventionPlanName: string;
  /**
   * @displayName Focus Area
   * @validationRule Required for create/update operations
   */
  focusAreaKey: InterventionPlanFocusAreaKey;
  /**
   * @displayName Grade Band
   * @validationRule Required for create/update operations
   */
  gradeBand: Pick<GradeBand, 'id' | 'gradeBandName'>;
  /**
   * @displayName Intervention Tier
   * @validationRule Required for create/update operations
   */
  interventionTier: Pick<InterventionTier, 'id' | 'interventionTierName'>;
  /**
   * @displayName Owner
   * @validationRule Required for create/update operations
   */
  owner: Pick<Staff, 'id' | 'staffName'>;
  /**
   * @displayName Program
   * @validationRule Required for create/update operations
   */
  program: Pick<Program, 'id' | 'programName'>;
  /**
   * @displayName School
   * @validationRule Required for create/update operations
   */
  school: Pick<School, 'id' | 'schoolName'>;
  /**
   * @displayName School Year
   * @validationRule Required for create/update operations
   */
  schoolYear: Pick<SchoolYear, 'id' | 'schoolYearName'>;
  /**
   * @displayName Start Date
   * @validationRule Required for create/update operations
   */
  startDate: string;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: InterventionPlanStatusKey;
  /**
   * @displayName Student Group
   * @validationRule Required for create/update operations
   */
  studentGroup: Pick<StudentGroup, 'id' | 'studentGroupName'>;
  /**
   * @displayName Target Date
   * @validationRule Required for create/update operations
   */
  targetDate: string;
  /**
   * @displayName Target Metric
   * @validationRule Required for create/update operations
   */
  targetMetric: string;
}

export const _InterventionPlan = 'InterventionPlan' as const;