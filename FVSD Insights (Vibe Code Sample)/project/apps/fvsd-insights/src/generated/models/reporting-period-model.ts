import type { SchoolYear } from './school-year-model';

export const ReportingPeriodPeriodTypeKeyToLabel = {
  'Month': 'Month',
  'Term': 'Term',
  'Semester': 'Semester',
  'YearToDate': 'Year To Date'
} as const;
export type ReportingPeriodPeriodTypeKey = keyof typeof ReportingPeriodPeriodTypeKeyToLabel;

export const ReportingPeriodStatusKeyToLabel = {
  'Open': 'Open',
  'Closed': 'Closed',
  'Published': 'Published'
} as const;
export type ReportingPeriodStatusKey = keyof typeof ReportingPeriodStatusKeyToLabel;

export interface ReportingPeriod {
  /**
   * @displayName Reporting Period ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Reporting Period Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  reportingPeriodName: string;
  /**
   * @displayName End Date
   * @validationRule Required for create/update operations
   */
  endDate: string;
  /**
   * @displayName Period Type
   * @validationRule Required for create/update operations
   */
  periodTypeKey: ReportingPeriodPeriodTypeKey;
  /**
   * @displayName School Year
   * @validationRule Required for create/update operations
   */
  schoolYear: Pick<SchoolYear, 'id' | 'schoolYearName'>;
  /**
   * @displayName Sequence Number
   * @validationRule Required for create/update operations
   */
  sequenceNumber: number;
  /**
   * @displayName Start Date
   * @validationRule Required for create/update operations
   */
  startDate: string;
  /**
   * @displayName Status
   * @validationRule Required for create/update operations
   */
  statusKey: ReportingPeriodStatusKey;
}

export const _ReportingPeriod = 'ReportingPeriod' as const;