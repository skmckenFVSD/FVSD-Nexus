import type { Staff } from './staff-model';
import type { GradeBand } from './grade-band-model';
import type { ReportingPeriod } from './reporting-period-model';
import type { School } from './school-model';
import type { StudentGroup } from './student-group-model';

export const AssistantInsightInsightTypeKeyToLabel = {
  'Trend': 'Trend',
  'EquityGap': 'Equity Gap',
  'Forecast': 'Forecast',
  'Anomaly': 'Anomaly',
  'Recommendation': 'Recommendation'
} as const;
export type AssistantInsightInsightTypeKey = keyof typeof AssistantInsightInsightTypeKeyToLabel;

export const AssistantInsightSeverityKeyToLabel = {
  'Low': 'Low',
  'Moderate': 'Moderate',
  'High': 'High',
  'Urgent': 'Urgent'
} as const;
export type AssistantInsightSeverityKey = keyof typeof AssistantInsightSeverityKeyToLabel;

export interface AssistantInsight {
  /**
   * @displayName Assistant Insight ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Assistant Insight Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  assistantInsightName: string;
  /**
   * @displayName Confidence Rate
   * @validationRule Required for create/update operations
   */
  confidenceRate: number;
  /**
   * @displayName Created By
   * @validationRule Required for create/update operations
   */
  createdBy: Pick<Staff, 'id' | 'staffName'>;
  /**
   * @displayName Created Date
   * @validationRule Required for create/update operations
   */
  createdDate: string;
  /**
   * @displayName Grade Band
   * @validationRule Required for create/update operations
   */
  gradeBand: Pick<GradeBand, 'id' | 'gradeBandName'>;
  /**
   * @displayName Insight Type
   * @validationRule Required for create/update operations
   */
  insightTypeKey: AssistantInsightInsightTypeKey;
  /**
   * @displayName Recommended Action
   * @validationRule Required for create/update operations
   */
  recommendedAction: string;
  /**
   * @displayName Reporting Period
   * @validationRule Required for create/update operations
   */
  reportingPeriod: Pick<ReportingPeriod, 'id' | 'reportingPeriodName'>;
  /**
   * @displayName School
   * @validationRule Required for create/update operations
   */
  school: Pick<School, 'id' | 'schoolName'>;
  /**
   * @displayName Severity
   * @validationRule Required for create/update operations
   */
  severityKey: AssistantInsightSeverityKey;
  /**
   * @displayName Student Group
   * @validationRule Required for create/update operations
   */
  studentGroup: Pick<StudentGroup, 'id' | 'studentGroupName'>;
  /**
   * @displayName Summary
   * @validationRule Required for create/update operations
   */
  summary: string;
}

export const _AssistantInsight = 'AssistantInsight' as const;