import type { GradeBand } from './grade-band-model';
import type { ReportingPeriod } from './reporting-period-model';
import type { School } from './school-model';
import type { StudentGroup } from './student-group-model';

export const AttendanceTrendTrendDirectionKeyToLabel = {
  'Improving': 'Improving',
  'Stable': 'Stable',
  'Declining': 'Declining'
} as const;
export type AttendanceTrendTrendDirectionKey = keyof typeof AttendanceTrendTrendDirectionKeyToLabel;

export interface AttendanceTrend {
  /**
   * @displayName Attendance Trend ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName Attendance Trend Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  attendanceTrendName: string;
  /**
   * @displayName Attendance Rate
   * @validationRule Required for create/update operations
   */
  attendanceRate: number;
  /**
   * @displayName Change From Prior Period
   * @validationRule Required for create/update operations
   */
  changeFromPriorPeriod: number;
  /**
   * @displayName Chronic Absenteeism Rate
   * @validationRule Required for create/update operations
   */
  chronicAbsenteeismRate: number;
  /**
   * @displayName Days In Session
   * @validationRule Required for create/update operations
   */
  daysInSession: number;
  /**
   * @displayName Excused Absences
   * @validationRule Required for create/update operations
   */
  excusedAbsences: number;
  /**
   * @displayName Grade Band
   * @validationRule Required for create/update operations
   */
  gradeBand: Pick<GradeBand, 'id' | 'gradeBandName'>;
  /**
   * @displayName Reporting Period
   * @validationRule Required for create/update operations
   */
  reportingPeriod: Pick<ReportingPeriod, 'id' | 'reportingPeriodName'>;
  /**
   * @displayName School
   * @validationRule Required for create/update operations
   */
  school: Pick<School, 'id' | 'schoolName'>;
  /**
   * @displayName Student Group
   * @validationRule Required for create/update operations
   */
  studentGroup: Pick<StudentGroup, 'id' | 'studentGroupName'>;
  /**
   * @displayName Trend Direction
   * @validationRule Required for create/update operations
   */
  trendDirectionKey: AttendanceTrendTrendDirectionKey;
  /**
   * @displayName Unexcused Absences
   * @validationRule Required for create/update operations
   */
  unexcusedAbsences: number;
}

export const _AttendanceTrend = 'AttendanceTrend' as const;