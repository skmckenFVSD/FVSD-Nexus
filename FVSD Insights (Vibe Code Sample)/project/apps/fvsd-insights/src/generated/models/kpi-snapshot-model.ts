import type { GradeBand } from './grade-band-model';
import type { Program } from './program-model';
import type { ReportingPeriod } from './reporting-period-model';
import type { School } from './school-model';
import type { StudentGroup } from './student-group-model';

export const KPISnapshotRiskLevelKeyToLabel = {
  'Low': 'Low',
  'Moderate': 'Moderate',
  'Elevated': 'Elevated',
  'Critical': 'Critical'
} as const;
export type KPISnapshotRiskLevelKey = keyof typeof KPISnapshotRiskLevelKeyToLabel;

export interface KPISnapshot {
  /**
   * @displayName KPI Snapshot ID
   * @description Unique system identifier - GUID generated by system
   * @uiConstraints NEVER create input fields for this ID
   */
  id: string;
  /**
   * @displayName KPI Snapshot Name
   * @description Human-readable record identifier
   * @validationRule Required for create/update operations
   */
  kPISnapshotName: string;
  /**
   * @displayName Attendance Rate
   * @validationRule Required for create/update operations
   */
  attendanceRate: number;
  /**
   * @displayName Grade Band
   * @validationRule Required for create/update operations
   */
  gradeBand: Pick<GradeBand, 'id' | 'gradeBandName'>;
  /**
   * @displayName Graduation On Track Rate
   * @validationRule Required for create/update operations
   */
  graduationOnTrackRate: number;
  /**
   * @displayName Intervention Completion Rate
   * @validationRule Required for create/update operations
   */
  interventionCompletionRate: number;
  /**
   * @displayName Literacy Proficiency Rate
   * @validationRule Required for create/update operations
   */
  literacyProficiencyRate: number;
  /**
   * @displayName Program
   * @validationRule Required for create/update operations
   */
  program: Pick<Program, 'id' | 'programName'>;
  /**
   * @displayName Reporting Period
   * @validationRule Required for create/update operations
   */
  reportingPeriod: Pick<ReportingPeriod, 'id' | 'reportingPeriodName'>;
  /**
   * @displayName Risk Level
   * @validationRule Required for create/update operations
   */
  riskLevelKey: KPISnapshotRiskLevelKey;
  /**
   * @displayName School
   * @validationRule Required for create/update operations
   */
  school: Pick<School, 'id' | 'schoolName'>;
  /**
   * @displayName Student Group
   * @validationRule Required for create/update operations
   */
  studentGroup: Pick<StudentGroup, 'id' | 'studentGroupName'>;
  /**
   * @displayName Wellbeing Index
   * @validationRule Required for create/update operations
   */
  wellbeingIndex: number;
}

export const _KPISnapshot = 'KPISnapshot' as const;