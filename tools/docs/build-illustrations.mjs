#!/usr/bin/env node
// Compose illustrations: <name>.base.webp (generated art, no text) +
// <name>.labels.svg (editable words and positions) → <name>.svg, a single
// self-contained SVG that renders on GitHub, in Obsidian and in the HTML builds.

import fs from 'node:fs'
import path from 'node:path'
import { DOCS } from './lib/common.mjs'

const DIR = path.join(DOCS, 'design-system', 'assets', 'illustrations')

for (const file of fs.readdirSync(DIR).filter((f) => f.endsWith('.labels.svg'))) {
  const name = file.replace(/\.labels\.svg$/, '')
  const labels = fs.readFileSync(path.join(DIR, file), 'utf8')
  const out = labels
    .replace(/<!--[\s\S]*?-->\s*/, `<!-- Generated by tools/docs/build-illustrations.mjs from ${file} and its base image. Edit the source files, not this one. -->\n`)
    .replace(/href="([^"]+\.(webp|png|jpe?g))"/g, (_, src, ext) => {
      const data = fs.readFileSync(path.join(DIR, src)).toString('base64')
      const mime = ext === 'jpg' ? 'jpeg' : ext
      return `href="data:image/${mime};base64,${data}"`
    })
  fs.writeFileSync(path.join(DIR, `${name}.svg`), out)
  console.log(`art   ${name}.svg (${Math.round(out.length / 1024)} KB)`)
}
